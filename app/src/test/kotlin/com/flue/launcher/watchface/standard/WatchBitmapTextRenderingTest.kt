package com.flue.launcher.watchface.standard

import android.graphics.Bitmap
import android.graphics.Color
import android.graphics.RectF
import java.io.File
import kotlinx.coroutines.runBlocking
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.RuntimeEnvironment
import org.robolectric.annotation.Config
import org.robolectric.annotation.GraphicsMode

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [28], manifest = Config.NONE)
@GraphicsMode(GraphicsMode.Mode.NATIVE)
class WatchBitmapTextRenderingTest {
    @get:Rule val temporaryFolder = TemporaryFolder()

    // Metrics from 洛明流萤改3.watch. Solid glyphs keep this fixture independent
    // of the author's artwork while exercising the actual parser and renderer.
    @Test
    fun hscMinutesKeepAuthoredTextSizeInsteadOfLayerHeight() {
        assertBounds(
            render(textSize = "56 * 2", layerHeight = 161, glyphWidth = 60, glyphHeight = 92),
            width = 233.73913f,
            height = 179.2f,
        )
    }

    @Test
    fun hscHoursApplyAnimationPercentOnceAfterAuthoredTextSize() {
        assertBounds(
            render(textSize = "126", layerHeight = 184, glyphWidth = 60, glyphHeight = 92,
                scaleX = 101, scaleY = 91),
            width = 265.5861f,
            height = 183.456f,
        )
    }

    @Test
    fun hscWeekdayKeepsAuthoredTextSizeInsteadOfLayerHeight() {
        assertBounds(
            render(textSize = "59", layerHeight = 84, glyphWidth = 118, glyphHeight = 46,
                text = "0"),
            width = 242.15652f,
            height = 94.4f,
        )
    }

    @Test
    fun hscBatteryAppliesAnimationPercentOnceAfterAuthoredTextSize() {
        assertBounds(
            render(textSize = "59", layerHeight = 85, glyphWidth = 32, glyphHeight = 46,
                text = "000", scaleX = 103, scaleY = 106),
            width = 202.91974f,
            height = 100.064f,
        )
    }

    @Test
    fun packageDescriptionAndOversizedAtlasDoNotChangeTheAuthoredSize() {
        val hsc = render(textSize = "60", layerHeight = 183, glyphWidth = 100, glyphHeight = 180)
        val regular = render(textSize = "60", layerHeight = 183, glyphWidth = 100,
            glyphHeight = 180, hscGenerated = false)
        assertEquals(regular, hsc)
        assertBounds(hsc, width = 106.66667f, height = 96f)
    }

    private fun render(
        textSize: String,
        layerHeight: Int,
        glyphWidth: Int,
        glyphHeight: Int,
        text: String = "00",
        scaleX: Int = 100,
        scaleY: Int = 100,
        hscGenerated: Boolean = true,
    ): RectF {
        val root = temporaryFolder.newFolder()
        val fonts = File(root, "fonts_bm").apply { mkdirs() }
        File(root, "watch.xml").writeText(
            """
            <Watch name="Bitmap sizing" shape="S" bg_color="000000"
                description="${if (hscGenerated) "Generated by HSC watchface downloader" else "Ordinary WatchMaker package"}">
                <Layer type="text" x="12" y="-8" width="1920" height="$layerHeight"
                    font="bm:fixture" text="$text" text_size="$textSize" alignment="cc"
                    opacity="100" display="bd" color="ffffff"
                    anim_scale_x="$scaleX" anim_scale_y="$scaleY"/>
            </Watch>
            """.trimIndent(),
        )
        File(fonts, "fixture.fnt").writeText(
            """
            info face="fixture" size=$glyphHeight
            common lineHeight=$glyphHeight base=0 scaleW=$glyphWidth scaleH=$glyphHeight pages=1
            page id=0 file="fixture.png"
            chars count=1
            char id=48 x=0 y=0 width=$glyphWidth height=$glyphHeight xoffset=0 yoffset=0 xadvance=$glyphWidth page=0
            """.trimIndent(),
        )
        val atlas = Bitmap.createBitmap(glyphWidth, glyphHeight, Bitmap.Config.ARGB_8888)
        atlas.eraseColor(Color.WHITE)
        File(fonts, "fixture.png").outputStream().use { atlas.compress(Bitmap.CompressFormat.PNG, 100, it) }
        atlas.recycle()

        val view = WatchmakerWatchFaceView(RuntimeEnvironment.getApplication())
        try {
            // Prepare synchronously so the test covers drawText without timing
            // assumptions about the host View's asynchronous bind lifecycle.
            val prepared = view.javaClass.getDeclaredMethod("prepareSource", File::class.java,
                Long::class.javaPrimitiveType).apply { isAccessible = true }.invoke(view, root, 0L)
            view.javaClass.getDeclaredField("source").apply { isAccessible = true }.set(view, prepared)
            runBlocking { view.prewarmBitmapFontAtlases() }
            val bitmap = requireNotNull(view.renderFaceBitmap(512))
            val bounds = RectF()
            var found = false
            for (y in 0 until bitmap.height) for (x in 0 until bitmap.width) {
                if (Color.red(bitmap.getPixel(x, y)) < 128) continue
                if (!found) bounds.set(x.toFloat(), y.toFloat(), x + 1f, y + 1f)
                else bounds.union(x.toFloat(), y.toFloat(), x + 1f, y + 1f)
                found = true
            }
            bitmap.recycle()
            assertTrue("The bitmap font must actually render", found)
            return bounds
        } finally {
            view.dispose()
        }
    }

    private fun assertBounds(actual: RectF, width: Float, height: Float) {
        // WFTools: glyph scale = 1.6 * text_size / info.size; animation is a
        // percentage multiplier. Pixel rounding may move each edge by one pixel.
        assertEquals("width", width, actual.width(), 2f)
        assertEquals("height", height, actual.height(), 2f)
        assertEquals("horizontal anchor", 268f, actual.centerX(), 1f)
        assertEquals("vertical anchor", 248f, actual.centerY(), 1f)
    }
}
